import re

for m in movies:
    title = m.get("title", "")
    if title in correct_years:
        m["year"] = correct_years[title]
    else:
        # If it has a year in parens like (Remake) or (2010), try to extract
        match = re.search(r'\((\d{4})\)', title)
        if match:
            m["year"] = int(match.group(1))
            
# Sort again by year
